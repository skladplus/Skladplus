#!/usr/bin/env bash
# Номер документа равен порядку чтения, README — полный указатель, ссылки ведут
# в существующие файлы. Проверяется всё три, потому что ломается обычно одно:
# документ переименован, а указатель и ссылки остались от прежней нумерации.
set -euo pipefail

cd "$(dirname "$0")/.."
fail=0
err() { echo "::error::$1"; fail=1; }

docs=()
while IFS= read -r f; do docs+=("$f"); done < <(git ls-files -- 'docs/[0-9][0-9]-*.md' | sort)
[ ${#docs[@]} -gt 0 ] || { err "в docs/ нет документов вида NN-имя.md — проверять нечего"; exit 1; }

# 1. Номер не повторяется: два документа с одним номером ломают сам смысл номера.
dupes=$(printf '%s\n' "${docs[@]}" | sed 's|docs/\(..\).*|\1|' | uniq -d)
[ -z "$dupes" ] || err "номер занят дважды: $(printf '%s ' $dupes)"

# 2. Заголовок документа несёт его собственный номер.
for f in "${docs[@]}"; do
  n=$(basename "$f" | cut -c1-2)
  head -1 "$f" | grep -qE "^# $n — " || err "$f: первая строка не «# $n — …»"
done

# 3. Указатель README сравнивается со списком документов один к одному: так
#    ловится и пропущенный документ, и лишний путь, и дубль строки, и порядок,
#    разошедшийся с нумерацией. Проверки «каждый найден» для этого мало.
index=$(grep -oE '\(docs/[0-9]{2}-[a-z-]+\.md\)' README.md | tr -d '()' || true)
if [ "$index" != "$(printf '%s\n' "${docs[@]}")" ]; then
  err "указатель README.md не совпадает со списком документов"
  diff <(printf '%s\n' "$index") <(printf '%s\n' "${docs[@]}") | sed 's/^/  /' || true
fi

# 4. Каждая ссылка на docs/ во всех отслеживаемых текстах ведёт в живой файл.
#    Скобка `(` в шаблоне оставляет только настоящие ссылки: упоминание пути
#    в прозе — не обещание, что файл есть.
while IFS= read -r hit; do
  file=${hit%%:*}; path=${hit#*:}
  [ -f "$path" ] || err "$file ссылается на несуществующий $path"
done < <(git ls-files -z -- '*.md' | xargs -0 -r grep -oHE '\(docs/[^)]+\.md' \
         | sed 's|:(|:|' || true)

# 5. Имя документа без `.md` — тоже ссылка: «решение строкой в 06-architecture»
#    после переименования указывает в никуда молча, потому что путём не выглядит.
#    Сверяем не по виду токена, а по смыслу: суффикс имени говорит, какой это
#    документ, и номер при нём обязан совпадать с настоящим. Поэтому «12-factor»
#    из прозы правило не трогает, а «02-architecture» после переезда — ловит.
#    Область та же, что у правил документов: журнал вправе называть старые имена.
map=$(printf '%s\n' "${docs[@]}" | sed 's|docs/\([0-9][0-9]\)-\(.*\)\.md|\2 \1|')
nums=$(printf '%s\n' "$map" | awk '{print $2}')
while IFS= read -r hit; do
  file=${hit%%:*}; stem=${hit#*:}; stem=${stem%.md}
  n=${stem%%-*}; suffix=${stem#*-}
  want=$(printf '%s\n' "$map" | awk -v s="$suffix" '$1 == s { print $2 }')
  if [ -n "$want" ]; then
    [ "$want" = "$n" ] || err "$file: $stem — документ теперь $want-$suffix"
  elif printf '%s\n' "$nums" | grep -qx "$n"; then
    err "$file: упоминает $stem, а документа с таким именем нет"
  fi
done < <(git ls-files -z -- 'docs/*.md' README.md AGENTS.md \
         | xargs -0 -r grep -oHE '[0-9]{2}-[a-z][a-z-]*(\.md)?' | sort -u || true)

[ "$fail" = 0 ] || exit 1
echo "документов: ${#docs[@]}, указатель полон, ссылки ведут в существующие файлы"
