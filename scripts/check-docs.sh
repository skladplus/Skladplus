#!/usr/bin/env bash
# Номер документа равен порядку чтения, README — полный указатель, ссылки ведут
# в существующие файлы. Проверяется всё три, потому что ломается обычно одно:
# документ переименован, а указатель и ссылки остались от прежней нумерации.
set -euo pipefail

cd "$(dirname "$0")/.."
fail=0
err() { echo "::error::$1"; fail=1; }

docs=()
while IFS= read -r f; do docs+=("$f"); done < <(git ls-files -- 'docs/[0-9][0-9]-*.md' | sort)
[ ${#docs[@]} -gt 0 ] || { err "в docs/ нет документов вида NN-имя.md — проверять нечего"; exit 1; }

# 1. Номер не повторяется: два документа с одним номером ломают сам смысл номера.
dupes=$(printf '%s\n' "${docs[@]}" | sed 's|docs/\(..\).*|\1|' | uniq -d)
[ -z "$dupes" ] || err "номер занят дважды: $(printf '%s ' $dupes)"

# 2. Заголовок документа несёт его собственный номер.
for f in "${docs[@]}"; do
  n=$(basename "$f" | cut -c1-2)
  head -1 "$f" | grep -qE "^# $n — " || err "$f: первая строка не «# $n — …»"
done

# 3. README перечисляет каждый документ и перечисляет их по возрастанию номера:
#    указатель, в котором порядок строк не совпадает с нумерацией, обманывает.
index=$(grep -oE '\(docs/[0-9]{2}-[a-z-]+\.md\)' README.md | tr -d '()' || true)
for f in "${docs[@]}"; do
  printf '%s\n' "$index" | grep -qx "$f" || err "$f нет в указателе README.md"
done
sorted=$(printf '%s\n' "$index" | sort)
[ "$index" = "$sorted" ] || err "в README.md документы идут не по возрастанию номера"

# 4. Каждая ссылка на docs/ во всех отслеживаемых текстах ведёт в живой файл.
#    Скобка `(` в шаблоне оставляет только настоящие ссылки: упоминание пути
#    в прозе — не обещание, что файл есть.
while IFS= read -r hit; do
  file=${hit%%:*}; path=${hit#*:}
  [ -f "$path" ] || err "$file ссылается на несуществующий $path"
done < <(git ls-files -z -- '*.md' | xargs -0 -r grep -oHE '\(docs/[^)]+\.md' \
         | sed 's|:(|:|' || true)

[ "$fail" = 0 ] || exit 1
echo "документов: ${#docs[@]}, указатель полон, ссылки ведут в существующие файлы"
